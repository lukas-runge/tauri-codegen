/// Generate TypeScript types file content
pub fn generate_types_file(
    structs: &[RustStruct],
    enums: &[RustEnum],
    aliases: &[RustTypeAlias],
    ctx: &GeneratorContext,
) -> String {
    let mut output = String::new();

    // Add header comment
    output.push_str("// This file was auto-generated by tauri-ts-generator\n");
    output.push_str("// Do not edit this file manually\n\n");

    // Generate interfaces for structs
    for s in structs {
        output.push_str(&generate_interface(s, ctx));
        output.push('\n');
    }

    // Generate types for enums
    let index = TypeIndex::new(structs, enums, aliases);
    for e in enums {
        output.push_str(&generate_enum_type(e, &index, ctx));
        output.push('\n');
    }

    // Generate type aliases
    for alias in aliases {
        output.push_str(&generate_alias_type(alias, ctx));
        output.push('\n');
    }

    output
}

/// Render a single struct field to TypeScript format (name, optional marker, type)
fn render_field(
    field: &crate::models::StructField,
    ctx: &GeneratorContext,
) -> (String, &'static str, String) {
    // If use_optional is true and type is Option<T>, generate field?: T instead of field: T | null
    let (optional_marker, ts_type) = if field.use_optional {
        if let crate::models::RustType::Option(inner) = &field.ty {
            ("?", rust_to_typescript(inner, ctx))
        } else {
            ("", rust_to_typescript(&field.ty, ctx))
        }
    } else {
        ("", rust_to_typescript(&field.ty, ctx))
    };

    // Field name already reflects serde configuration from parser
    // (rename, rename_all, or original name if no serde attrs)
    let field_name = property_key(&field.name).into_owned();

    (field_name, optional_marker, ts_type)
}

/// Generate a TypeScript interface from a Rust struct
/// If the struct has #[serde(flatten)] fields, generate a type alias with intersection
fn generate_interface(s: &RustStruct, ctx: &GeneratorContext) -> String {
    let mut output = String::new();

    let interface_name = ctx.format_type_name(&s.name);

    // Add generic parameters if present
    let generics_str = if s.generics.is_empty() {
        String::new()
    } else {
        format!("<{}>", s.generics.join(", "))
    };

    // Non-named shapes (unit / newtype / tuple) serialize without an object
    // wrapper — render them as type aliases that match the JSON shape.
    match s.shape {
        StructShape::Unit => {
            return format!("export type {}{} = null;\n", interface_name, generics_str);
        }
        StructShape::Newtype if s.fields.len() == 1 => {
            let inner = rust_to_typescript(&s.fields[0].ty, ctx);
            return format!(
                "export type {}{} = {};\n",
                interface_name, generics_str, inner
            );
        }
        StructShape::Tuple => {
            let elems: Vec<String> = s
                .fields
                .iter()
                .map(|f| rust_to_typescript(&f.ty, ctx))
                .collect();
            return format!(
                "export type {}{} = [{}];\n",
                interface_name,
                generics_str,
                elems.join(", ")
            );
        }
        _ => {}
    }

    // Separate normal fields from flattened fields
    let (flatten_fields, normal_fields): (Vec<_>, Vec<_>) =
        s.fields.iter().partition(|f| f.is_flatten);

    // `#[serde(flatten)]` requires the flattened field to serialize as a
    // map. A bare string-union enum (external-tagged unit variants like
    // `enum Role { Admin, User }`) serializes as a string, which at
    // runtime panics in serde — and in TypeScript an intersection
    // `{ … } & "Admin" | "User"` silently reduces to `never`. Warn so
    // the user notices the misuse instead of only finding out at runtime.
    for flat in &flatten_fields {
        if let crate::models::RustType::Custom { name, .. } = &flat.ty {
            let simple = crate::utils::simple_name(name);
            if ctx.is_enum(simple) {
                crate::diagnostics::warn(format!(
                    "#[serde(flatten)] on field '{}' of struct '{}' targets enum '{}'. \
                    Serde requires flatten targets to serialize as a map, and a plain \
                    enum's string union intersects to `never` in TypeScript. \
                    Use a tag/content representation on '{}' or drop the flatten.",
                    flat.name, s.name, simple, simple
                ));
            }
        }
    }

    if flatten_fields.is_empty() {
        // No flatten fields - generate regular interface
        output.push_str(&format!(
            "export interface {}{} {{\n",
            interface_name, generics_str
        ));

        for field in &s.fields {
            let (field_name, optional_marker, ts_type) = render_field(field, ctx);
            output.push_str(&format!(
                "  {}{}: {};\n",
                field_name, optional_marker, ts_type
            ));
        }

        output.push_str("}\n");
    } else {
        // Has flatten fields - generate type alias with intersection
        output.push_str(&format!(
            "export type {}{} = ",
            interface_name, generics_str
        ));

        // Generate inline object for normal fields
        if normal_fields.is_empty() {
            // No normal fields, start with first flatten type
            let mut flatten_types: Vec<String> = flatten_fields
                .iter()
                .map(|f| rust_to_typescript(&f.ty, ctx))
                .collect();
            output.push_str(&flatten_types.remove(0));
            for ft in flatten_types {
                output.push_str(&format!(" & {}", ft));
            }
        } else {
            // Generate inline object for normal fields
            output.push_str("{\n");
            for field in normal_fields {
                let (field_name, optional_marker, ts_type) = render_field(field, ctx);
                output.push_str(&format!(
                    "  {}{}: {};\n",
                    field_name, optional_marker, ts_type
                ));
            }
            output.push('}');

            // Add intersection with flatten types
            for field in flatten_fields {
                let ts_type = rust_to_typescript(&field.ty, ctx);
                output.push_str(&format!(" & {}", ts_type));
            }
        }

        output.push_str(";\n");
    }

    output
}

/// Generate a TypeScript type from a Rust enum. `index` holds the other
/// generated types, to check what internally tagged newtype variants wrap.
fn generate_enum_type(e: &RustEnum, index: &TypeIndex, ctx: &GeneratorContext) -> String {
    let mut output = String::new();

    let type_name = ctx.format_type_name(&e.name);

    // Add generic parameters if present
    let generics_str = if e.generics.is_empty() {
        String::new()
    } else {
        format!("<{}>", e.generics.join(", "))
    };

    let variants: Vec<String> = e
        .variants
        .iter()
        .map(|variant| generate_variant(variant, e, index, ctx))
        .collect();

    if variants.is_empty() {
        output.push_str(&format!(
            "export type {}{} = never;\n",
            type_name, generics_str
        ));
    } else {
        output.push_str(&format!(
            "export type {}{} =\n  | {};\n",
            type_name,
            generics_str,
            variants.join("\n  | ")
        ));
    }

    output
}

fn generate_variant(
    variant: &crate::models::EnumVariant,
    e: &RustEnum,
    index: &TypeIndex,
    ctx: &GeneratorContext,
) -> String {
    match &e.representation {
        EnumRepresentation::External => match &variant.data {
            VariantData::Unit => string_literal(&variant.name),
            VariantData::Tuple(types) => {
                let ts_types: Vec<_> = types.iter().map(|t| rust_to_typescript(t, ctx)).collect();
                let inner = if ts_types.len() == 1 {
                    ts_types[0].clone()
                } else {
                    format!("[{}]", ts_types.join(", "))
                };
                format!("{{ {}: {} }}", property_key(&variant.name), inner)
            }
            VariantData::Struct(fields) => {
                let inner = generate_struct_body(fields, ctx);
                format!("{{ {}: {} }}", property_key(&variant.name), inner)
            }
        },
        EnumRepresentation::Internal { tag } => {
            let tag = property_key(tag);
            let name = string_literal(&variant.name);
            match &variant.data {
                VariantData::Unit => format!("{{ {}: {} }}", tag, name),
                VariantData::Struct(fields) => {
                    let mut body = generate_struct_body(fields, ctx);
                    // Remove opening brace and insert tag
                    body.remove(0); // remove '{'
                    format!("{{ {}: {},{}", tag, name, body)
                }
                VariantData::Tuple(types) => {
                    // Serde's internal tagging doesn't support tuple variants (it errors at runtime).
                    // A newtype (single element) works when the inner type
                    // serializes as an object: serde merges the tag into it.
                    if types.len() == 1 {
                        let inner_ts = rust_to_typescript(&types[0], ctx);
                        match index.inner_shape(&types[0]) {
                            InnerShape::Object => {}
                            // Only the tag is left; `{ … } & null` would be `never`.
                            InnerShape::Empty => return format!("{{ {}: {} }}", tag, name),
                            InnerShape::Rejected(what) => crate::diagnostics::warn(format!(
                                "Internally tagged variant '{}' of enum '{}' wraps {}. Serde \
                                can only add the tag to an object and fails at runtime \
                                (\"cannot serialize tagged newtype variant\"). Use a struct \
                                variant or adjacent tagging instead.",
                                variant.name, e.name, what
                            )),
                            InnerShape::Uncertain(why) => crate::diagnostics::warn(format!(
                                "The generated type of internally tagged variant '{}' of \
                                enum '{}' may not match serde: {}. Consider adjacent \
                                tagging instead.",
                                variant.name, e.name, why
                            )),
                        }
                        // Generate: { tag: "Name" } & InnerType
                        let inner_ts = if inner_ts.contains('|') {
                            format!("({})", inner_ts)
                        } else {
                            inner_ts
                        };
                        format!("({{ {}: {} }} & {})", tag, name, inner_ts)
                    } else {
                        crate::diagnostics::warn(format!(
                            "Internal tagging does not support tuple variants with \
                            multiple elements (variant '{}'). Serde will error at runtime. \
                            Consider using external or adjacent tagging instead.",
                            variant.name
                        ));
                        // Fall back to just the tag since this won't work in serde anyway
                        format!("{{ {}: {} }}", tag, name)
                    }
                }
            }
        }
        EnumRepresentation::Adjacent { tag, content } => {
            let tag = property_key(tag);
            let content = property_key(content);
            let name = string_literal(&variant.name);
            match &variant.data {
                VariantData::Unit => format!("{{ {}: {} }}", tag, name),
                VariantData::Tuple(types) => {
                    let ts_types: Vec<_> =
                        types.iter().map(|t| rust_to_typescript(t, ctx)).collect();
                    let inner = if ts_types.len() == 1 {
                        ts_types[0].clone()
                    } else {
                        format!("[{}]", ts_types.join(", "))
                    };
                    format!("{{ {}: {}; {}: {} }}", tag, name, content, inner)
                }
                VariantData::Struct(fields) => {
                    let inner = generate_struct_body(fields, ctx);
                    format!("{{ {}: {}; {}: {} }}", tag, name, content, inner)
                }
            }
        }
        EnumRepresentation::Untagged => match &variant.data {
            VariantData::Unit => "null".to_string(), // Untagged unit matches null? Or nothing? Serde says it errors if it can't match. Usually untagged is for matching shapes.
            VariantData::Tuple(types) => {
                let ts_types: Vec<_> = types.iter().map(|t| rust_to_typescript(t, ctx)).collect();
                if ts_types.len() == 1 {
                    ts_types[0].clone()
                } else {
                    format!("[{}]", ts_types.join(", "))
                }
            }
            VariantData::Struct(fields) => generate_struct_body(fields, ctx),
        },
    }
}

/// Generate a TypeScript type alias from a Rust type alias
fn generate_alias_type(alias: &RustTypeAlias, ctx: &GeneratorContext) -> String {
    let alias_name = ctx.format_type_name(&alias.name);

    let generics_str = if alias.generics.is_empty() {
        String::new()
    } else {
        format!("<{}>", alias.generics.join(", "))
    };

    let target_ts = rust_to_typescript(&alias.target, ctx);

    format!(
        "export type {}{} = {};\n",
        alias_name, generics_str, target_ts
    )
}

/// Render `name` as a TypeScript object property key: bare when it's a
/// valid identifier (`datePart`, `type`), quoted otherwise (`"date-part"`,
/// `"2fa"`). Serde field names come from `rename`/`rename_all` and can
/// contain anything.
fn property_key(name: &str) -> Cow<'_, str> {
    if is_identifier(name) {
        Cow::Borrowed(name)
    } else {
        Cow::Owned(string_literal(name))
    }
}

/// Whether `name` can be written as a bare property key. Reserved words
/// are fine as property names (`{ type: string }`), so only the character
/// rules of identifiers matter.
fn is_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    let is_start = |c: char| c.is_alphabetic() || c == '_' || c == '$';
    is_start(first) && chars.all(|c| is_start(c) || c.is_alphanumeric())
}

/// Render `value` as a double-quoted TypeScript string literal.
fn string_literal(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn generate_struct_body(fields: &[crate::models::StructField], ctx: &GeneratorContext) -> String {
    let params: Vec<String> = fields
        .iter()
        .map(|field| {
            let (field_name, optional_marker, ts_type) = render_field(field, ctx);
            format!("{}{}: {}", field_name, optional_marker, ts_type)
        })
        .collect();
    format!("{{ {} }}", params.join("; "))
}

